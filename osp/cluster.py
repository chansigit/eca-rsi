def _paga_table(ad, cluster_key):
    """Cluster x cluster PAGA connectivity matrix from sc.tl.paga (cluster
    connectivity computed over the KNN graph in ad.obsp["connectivities"])."""
    conn = ad.uns["paga"]["connectivities"]
    labels = ad.obs[cluster_key].cat.categories.astype(str)
    df = pd.DataFrame(conn.toarray(), index=labels, columns=labels)
    df.index.name = cluster_key
    return df


